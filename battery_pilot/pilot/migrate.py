"""Take over from Battery Playbook 1.x.

The old app wrote YAML packages whose automations drive the same inverter.
Left running they would fight this app, so first their automations are
switched off, then their data is taken over (12 months of contract history,
consumption average, this month's peak), and finally their package files are
removed (a copy goes to the app's storage) and HA reloads its YAML.
"""
from __future__ import annotations

import logging
import os
import re
import shutil
from datetime import datetime
from zoneinfo import ZoneInfo

log = logging.getLogger(__name__)

MARK = "# Generated by the Battery Playbook app"
OLD_AUTOMATIONS = {
    "ps_winter_mode_auto", "ps_night_start", "ps_follow_load", "ps_target_reached", "ps_window_end",
    "ps_peak_warning", "dyn_apply_plan", "dyn_switch_off", "dyn_curtail_negative", "cw_first_run_defaults",
    "cw_monthly_verdict", "cw_renewal_reminder", "cw_rates_changed", "cw_breakeven_cross",
}
PKG_LINE = re.compile(r"^\s+packages:\s*!include_dir_named\s+(\S+)\s*(#.*)?$", re.M)


def find_old_packages(config_dir: str) -> list[str]:
    dirs = [os.path.join(config_dir, "packages")]
    try:
        text = open(os.path.join(config_dir, "configuration.yaml"), encoding="utf-8").read()
        m = PKG_LINE.search(text)
        if m:
            dirs.insert(0, os.path.join(config_dir, m.group(1)))
    except OSError:
        pass
    found = []
    for d in dict.fromkeys(dirs):
        for root, _, files in os.walk(d):
            for fn in files:
                if fn.endswith((".yaml", ".yml")):
                    p = os.path.join(root, fn)
                    try:
                        with open(p, encoding="utf-8") as f:
                            if f.read(len(MARK)) == MARK:
                                found.append(p)
                    except OSError:
                        continue
    return sorted(found)


def import_history(states: dict, comparison) -> list[str]:
    """Months from the old shadow bill (same-usage view) into the comparison."""
    attrs = (states.get("sensor.cw_shadow_bill") or {}).get("attributes") or {}
    hist = list(attrs.get("hist") or [])
    cur = attrs.get("cur")
    if isinstance(cur, dict) and cur.get("month") and cur.get("n"):
        hist.append({**cur, "belpex": cur.get("p_sum", 0) / max(cur.get("n", 1), 1)})
    n = 0
    for m in hist:
        try:
            key = str(m["month"])
            if key in comparison.months:
                continue
            acc = comparison.month(key)
            for k in ("imp_day", "imp_night", "exp"):      # (the whole month had a market price)
                acc[k] = acc["p_" + k] = float(m.get(k, 0))
            acc["market_sum"] = float(m.get("belpex", 0))
            acc["market_n"] = 1
            acc["dyn_c"] = (float(m.get("dyn_imp", 0)) - float(m.get("dyn_exp", 0))) * 100
            comparison.imported[key] = "same-usage figures from Battery Playbook"
            n += 1
        except (KeyError, TypeError, ValueError):
            continue
    return [f"  took over {n} month(s) of contract history from Battery Playbook"] if n else []


def _float(states, eid):
    try:
        return float((states.get(eid) or {}).get("state"))
    except (TypeError, ValueError):
        return None


async def migrate(ha, states: dict, config_dir: str | None, backup_dir: str, comparison, load, peaks,
                  now: datetime, tz: ZoneInfo) -> list[str]:
    old_autos = [eid for eid, s in states.items() if eid.startswith("automation.")
                 and (s.get("attributes") or {}).get("id") in OLD_AUTOMATIONS]
    files = find_old_packages(config_dir) if config_dir else []
    if not old_autos and not files:
        return []
    notes = ["Battery Playbook found: taking over"]
    on = [eid for eid in old_autos if states[eid].get("state") == "on"]
    if on:
        await ha.call("automation", "turn_off", {"entity_id": on})
        notes.append(f"  switched off {len(on)} old automation(s) so they cannot drive the inverter")
    notes += import_history(states, comparison)
    avg = _float(states, "sensor.ps_daily_consumption_avg")
    if avg and avg > 0 and not load.learned():
        load.default_kw = avg / 24
        notes.append(f"  starting from your average consumption of {avg:.1f} kWh/day")
    peak = _float(states, "sensor.ps_monthly_peak")
    if peak:
        key = now.astimezone(tz).strftime("%Y-%m")
        peaks.months[key] = max(peaks.months.get(key, 0.0), peak)
    if files:
        os.makedirs(backup_dir, exist_ok=True)
        saved = {}
        for p in files:
            saved[p] = open(p, encoding="utf-8").read()
            shutil.copy(p, os.path.join(backup_dir, os.path.basename(p)))
            os.remove(p)
        try:
            ok, errors = await ha.check_config()
        except Exception as e:  # noqa: BLE001
            ok, errors = False, str(e)
        if not ok:
            for p, text in saved.items():
                with open(p, "w", encoding="utf-8") as f:
                    f.write(text)
            notes.append("  kept the old package files: HA's configuration check failed without them "
                         f"({str(errors)[:200]}). Their automations stay switched off.")
        else:
            notes.append(f"  removed {len(files)} old package file(s) (copies in the app's storage)")
            try:
                await ha.call("homeassistant", "reload_all")
            except Exception:  # noqa: BLE001 - older HA: a restart does the same
                pass
            await ha.call("persistent_notification", "create", {
                "title": "Battery Pilot took over from Battery Playbook",
                "message": "Restart Home Assistant once to remove the old Battery Playbook sensors, "
                           "then uninstall the Battery Playbook app.",
                "notification_id": "battery_pilot_migration"})
    return notes
