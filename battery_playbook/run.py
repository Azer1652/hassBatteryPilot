#!/usr/bin/env python3
"""Battery Playbook app.

Writes the peak-shaving, dynamic-tariff and contract-watch packages into Home
Assistant's packages folder, filled in with your entities and settings, checks
the configuration and restarts Home Assistant when something changed.
Runs once and stops: change a setting, press Start again.
"""
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request

VERSION = os.environ.get("BP_VERSION", "1.0.0")
OPTIONS_FILE = os.environ.get("BP_OPTIONS", "/data/options.json")
TEMPLATES = os.environ.get("BP_TEMPLATES", "/app/templates")
API = os.environ.get("BP_API", "http://supervisor/core/api")
TOKEN = os.environ.get("SUPERVISOR_TOKEN", "")
BACKUP_DIR = os.environ.get("BP_BACKUP", "/data/backup")
MARK = "# Generated by the Battery Playbook app"
PACKAGES = {
    "peak_shaving": "battery_playbook_peak_shaving.yaml",
    "dynamic_tariff": "battery_playbook_dynamic_tariff.yaml",
    "contract_watch": "battery_playbook_contract_watch.yaml",
}
# Helpers each package defines: used to spot manual copies that would clash.
SIGNATURES = {"peak_shaving": "ps_inverter:", "dynamic_tariff": "dyn_enabled:", "contract_watch": "cw_contract:"}

# key: (domain, search patterns in order, required, is power sensor, fallback placeholder)
ENTITIES = {
    "grid_import_power": ("sensor", [r"grid_import_power", r"import_power"], True, True, "sensor.solis_grid_import_power"),
    "grid_export_power": ("sensor", [r"grid_export_power", r"(?<!limit_)export_power$"], False, True, "sensor.solis_grid_export_power"),
    "house_load_power": ("sensor", [r"household_load_power", r"house(hold)?_load", r"load_power"], True, True, "sensor.solis_household_load_power"),
    "battery_soc": ("sensor", [r"battery_soc$", r"battery_soc"], True, False, "sensor.solis_battery_soc"),
    "battery_voltage": ("sensor", [r"battery_voltage$", r"battery_voltage"], False, False, "sensor.solis_battery_voltage"),
    "pv_power": ("sensor", [r"total_pv_power", r"pv_power$"], False, True, "sensor.solis_total_pv_power"),
    "battery_discharge_power": ("sensor", [r"battery_discharge_power"], False, True, "sensor.solis_battery_discharge_power"),
    "tou_switch": ("switch", [r"time_of_use$", r"time_of_use"], True, False, "switch.solis_time_of_use"),
    "grid_charge_switch": ("switch", [r"allow_grid.*charg", r"grid_charg"], True, False, "switch.solis_allow_grid_to_charge_the_battery"),
    "charge_current": ("number", [r"(?<!dis)charge_current"], True, False, "number.solis_time_charging_charge_current"),
    "discharge_current": ("number", [r"discharge_current"], True, False, "number.solis_time_charging_discharge_current"),
    "charge_start": ("time", [r"(?<!dis)charge_start.*slot_1$"], True, False, "time.solis_time_charging_charge_start_slot_1"),
    "charge_end": ("time", [r"(?<!dis)charge_end.*slot_1$"], True, False, "time.solis_time_charging_charge_end_slot_1"),
    "discharge_start": ("time", [r"discharge_start.*slot_1$"], True, False, "time.solis_time_charging_discharge_start_slot_1"),
    "discharge_end": ("time", [r"discharge_end.*slot_1$"], True, False, "time.solis_time_charging_discharge_end_slot_1"),
    "export_limit": ("number", [r"export_power_limit", r"export.*limit"], False, False, "number.solis_export_power_limit"),
    "forecast_today": ("sensor", [r"^energy_production_today$"], False, False, "sensor.energy_production_today"),
    "forecast_today_remaining": ("sensor", [r"^energy_production_today_remaining$"], False, False, "sensor.energy_production_today_remaining"),
    "forecast_tomorrow": ("sensor", [r"^energy_production_tomorrow$"], False, False, "sensor.energy_production_tomorrow"),
    "entsoe_price": ("sensor", [r"current_electricity_market_price"], False, False, "sensor.current_electricity_market_price"),
}
# Which package needs which entity (for warnings only).
NEEDED_BY = {"grid_export_power": "contract_watch", "entsoe_price": "dynamic_tariff and contract_watch",
             "export_limit": "the negative-price export block", "forecast_today": "the tree correction",
             "forecast_today_remaining": "the night target", "forecast_tomorrow": "winter mode and the night target",
             "pv_power": "the tree correction", "battery_discharge_power": "the cycle counter",
             "battery_voltage": "the charge current (51.2 V is assumed without it)"}
TIME_SLOT_KEYS = ("charge_start", "charge_end", "discharge_start", "discharge_end")


def log(msg=""):
    print(msg, flush=True)


class Stop(Exception):
    """Abort with a message for the log; nothing more is written."""


def api(method, path, body=None, timeout=90):
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(API + path, data=data, method=method,
                                 headers={"Authorization": f"Bearer {TOKEN}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        text = r.read().decode()
    return json.loads(text) if text.strip() else None


def wait_for_home_assistant(max_wait=600):
    start = time.time()
    while True:
        try:
            api("GET", "/")
            return
        except Exception as e:  # noqa: BLE001 - any failure means "not ready yet"
            if time.time() - start > max_wait:
                raise Stop(f"Home Assistant's API did not answer within {max_wait // 60} minutes ({e}).")
            time.sleep(10)


def config_dir():
    for d in (os.environ.get("BP_CONFIG_DIR"), "/homeassistant", "/config"):
        if d and os.path.isfile(os.path.join(d, "configuration.yaml")):
            return d
    raise Stop("Can't find configuration.yaml. Is the app allowed to access the Home Assistant configuration folder?")


# ---------------------------------------------------------------- entities
def pick_slot_set(found, slot_set):
    if slot_set == "time_charging":
        narrowed = [e for e in found if "time_charging" in e]
    else:
        narrowed = [e for e in found if "time_charging" not in e]
    return narrowed or found


def resolve(key, opts, states):
    domain, patterns, required, is_power, fallback = ENTITIES[key]
    chosen = (opts.get(key) or "").strip()
    if chosen:
        if chosen not in states:
            return None, f"set to {chosen}, but Home Assistant has no entity with that ID"
        return chosen, "set in the app settings"
    ids = sorted(e for e in states if e.startswith(domain + "."))
    for p in patterns:
        found = [e for e in ids if re.search(p, e.split(".", 1)[1])]
        if key in TIME_SLOT_KEYS or key in ("charge_current", "discharge_current"):
            found = pick_slot_set(found, opts.get("slot_entities", "time_charging"))
        if len(found) == 1:
            return found[0], "found automatically"
        if len(found) > 1:
            solis = [e for e in found if "solis" in e]
            if len(solis) == 1:
                return solis[0], "found automatically"
            return None, "several candidates, pick one in the settings: " + ", ".join(found[:6])
    return None, "not found"


def power_scale(eid, states):
    unit = (states.get(eid, {}).get("attributes", {}) or {}).get("unit_of_measurement", "")
    if unit == "kW":
        return "1", unit
    if unit == "W":
        return "0.001", unit
    return "0.001", unit or "no unit"


def find_notify(opts):
    chosen = (opts.get("notify_service") or "").strip()
    if chosen:
        return (chosen if chosen.startswith("notify.") else "notify." + chosen), "set in the app settings"
    try:
        services = api("GET", "/services") or []
    except Exception:  # noqa: BLE001
        services = []
    phones = []
    for dom in services:
        if dom.get("domain") == "notify":
            phones = sorted(s for s in (dom.get("services") or {}) if s.startswith("mobile_app_"))
    if len(phones) == 1:
        return "notify." + phones[0], "found automatically"
    if len(phones) > 1:
        return "notify.notify", "several phones found (" + ", ".join(phones) + "): set notify_service to pick one"
    return "notify.notify", "no Companion app found: install it and press Start again"


# ---------------------------------------------------------------- configuration.yaml
PKG_LINE = re.compile(r"^\s+packages:\s*!include_dir_named\s+(\S+)\s*(#.*)?$", re.M)
ANY_PKG = re.compile(r"^\s+packages:", re.M)


def packages_dir(cfg, opts, changes):
    path = os.path.join(cfg, "configuration.yaml")
    text = open(path, encoding="utf-8").read()
    m = PKG_LINE.search(text)
    if m:
        return os.path.join(cfg, m.group(1))
    if ANY_PKG.search(text):
        raise Stop("configuration.yaml already loads packages in another way than '!include_dir_named'. "
                   "Change that line to 'packages: !include_dir_named packages', then press Start again.")
    if not opts.get("auto_configure_packages", True):
        raise Stop("configuration.yaml has no packages line. Add under 'homeassistant:' the line "
                   "'  packages: !include_dir_named packages', or switch on auto_configure_packages.")
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if re.match(r"^homeassistant:\s*(#.*)?$", line):
            lines.insert(i + 1, "  packages: !include_dir_named packages\n")
            break
        if re.match(r"^homeassistant:\s*\S", line):
            raise Stop("Your 'homeassistant:' section is loaded from another file. Add "
                       "'packages: !include_dir_named packages' there, then press Start again.")
    else:
        if lines and not lines[-1].endswith("\n"):
            lines[-1] += "\n"
        lines += ["\nhomeassistant:\n", "  packages: !include_dir_named packages\n"]
    changes.append((path, text))
    with open(path, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    log("  added 'packages: !include_dir_named packages' to configuration.yaml (backup kept until the check passes)")
    return os.path.join(cfg, "packages")


def manual_copies(pdir, wanted):
    clashes = []
    for root, _, files in os.walk(pdir):
        for fn in files:
            if not fn.endswith((".yaml", ".yml")):
                continue
            p = os.path.join(root, fn)
            try:
                head = open(p, encoding="utf-8").read()
            except OSError:
                continue
            if head.startswith(MARK):
                continue
            for pkg in wanted:
                if SIGNATURES[pkg] in head:
                    clashes.append(os.path.relpath(p, os.path.dirname(pdir)))
    return sorted(set(clashes))


# ---------------------------------------------------------------- main steps
def render(pkg, values):
    text = open(os.path.join(TEMPLATES, pkg + ".yaml"), encoding="utf-8").read()
    for k, v in values.items():
        text = text.replace(f"@@{k}@@", str(v))
    left = sorted(set(re.findall(r"@@[a-z_]+@@", text)))
    if left:
        raise Stop(f"Internal error: unfilled settings {left} in {pkg}.")
    header = (f"{MARK} {VERSION}.\n# Don't edit this file: change the app's settings and press Start.\n"
              "# Your edits here are overwritten on the next run.\n\n")
    return header + text


def check_config():
    try:
        res = api("POST", "/config/core/check_config", {}, timeout=180) or {}
    except urllib.error.HTTPError as e:
        return False, f"check failed with HTTP {e.code}"
    return res.get("result") == "valid", res.get("errors") or ""


def restart():
    try:
        api("POST", "/services/homeassistant/restart", {}, timeout=30)
    except Exception:  # noqa: BLE001 - the connection drops while Home Assistant restarts
        pass


def rollback(changes):
    for path, old in reversed(changes):
        if old is None:
            if os.path.exists(path):
                os.remove(path)
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(old)


def main():
    opts = json.load(open(OPTIONS_FILE, encoding="utf-8"))
    log(f"Battery Playbook {VERSION}")
    cfg = config_dir()
    log("Waiting for Home Assistant…")
    wait_for_home_assistant()
    changes = []  # (path, previous content or None) for rollback

    wanted = [p for p in PACKAGES if opts.get(f"install_{p}", True)]
    if "peak_shaving" not in wanted and wanted:
        log("! dynamic_tariff and contract_watch need peak_shaving: they are skipped too.")
        wanted = []
    if opts.get("remove_packages"):
        wanted = []
        log("remove_packages is on: removing every file this app wrote.")

    pdir = packages_dir(cfg, opts, changes)
    os.makedirs(pdir, exist_ok=True)

    clashes = manual_copies(pdir, wanted)
    if clashes:
        rollback(changes)
        raise Stop("These files define the same helpers as this app and would clash: " + ", ".join(clashes) +
                   ". Delete or rename them (to .bak), then press Start again.")

    values = {}
    if wanted:
        states = {s["entity_id"]: s for s in api("GET", "/states")}
        log("")
        log("Entities")
        missing_required = []
        for key, (domain, _, required, is_power, fallback) in ENTITIES.items():
            eid, how = resolve(key, opts, states)
            if eid is None:
                values[key] = fallback
                tag = "MISSING" if required else "missing"
                log(f"  {tag:8} {key}: {how}" + (f" (needed for {NEEDED_BY[key]})" if key in NEEDED_BY else ""))
                if required:
                    missing_required.append(key)
                if is_power:
                    values[key + "_scale"] = "0.001"
                continue
            values[key] = eid
            extra = ""
            if is_power:
                scale, unit = power_scale(eid, states)
                values[key + "_scale"] = scale
                extra = f" [{unit}]"
                if unit not in ("W", "kW"):
                    extra += " assumed W"
            log(f"  ok       {key}: {eid}{extra} ({how})")
        if missing_required:
            rollback(changes)
            raise Stop("Required entities are missing: " + ", ".join(missing_required) +
                       ". Set them on the app's Configuration tab (Show unused optional configuration options), "
                       "then press Start again.")
        notify, how = find_notify(opts)
        values["notify_service"] = notify
        log(f"  {'check' if notify == 'notify.notify' else 'ok':8} notify_service: {notify} ({how})")
        values.update({
            "import_limit": opts.get("import_limit_kw", 2.3),
            "night_margin": opts.get("night_margin_pct", 30),
            "window_start": opts.get("night_window_start", "22:00") + ":00",
            "window_end": opts.get("night_window_end", "07:00") + ":00",
            "grid_fees": opts.get("grid_fees_c_kwh", 11.96),
            "capacity": opts.get("capacity_eur_kw_year", 52.37),
            "fixed_day": opts.get("fixed_day_rate", 18.59),
            "fixed_night": opts.get("fixed_night_rate", 15.22),
        })

    log("")
    log(f"Packages in {os.path.relpath(pdir, cfg)}/")
    for pkg, fn in PACKAGES.items():
        path = os.path.join(pdir, fn)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if pkg in wanted:
            new = render(pkg, values)
            if new != old:
                changes.append((path, old))
                with open(path, "w", encoding="utf-8") as f:
                    f.write(new)
                log(f"  {'updated' if old else 'written'}  {fn}")
            else:
                log(f"  unchanged {fn}")
        elif old is not None and old.startswith(MARK):
            changes.append((path, old))
            os.remove(path)
            log(f"  removed  {fn}")

    if not changes:
        log("")
        log("Nothing changed, so Home Assistant keeps running as it is.")
        return 0

    log("")
    log("Checking the configuration…")
    ok, errors = check_config()
    if not ok:
        rollback(changes)
        raise Stop("Home Assistant rejected the configuration, so every change was undone.\n" + str(errors))
    log("  configuration is valid")
    # Keep the previous version of each changed file, so a bad update can be undone by hand.
    os.makedirs(BACKUP_DIR, exist_ok=True)
    for path, old in changes:
        if old is not None:
            with open(os.path.join(BACKUP_DIR, os.path.basename(path) + ".previous"), "w", encoding="utf-8") as f:
                f.write(old)
    if opts.get("restart_home_assistant", True):
        log("Restarting Home Assistant to load the changes.")
        restart()
    else:
        log("Restart Home Assistant to load the changes (restart_home_assistant is off).")
    log("")
    log("Next: open Settings → Devices & services → Helpers and switch on 'Peak shaving enabled' "
        "once you have done the test in the guide.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Stop as e:
        log("")
        log(f"STOPPED: {e}")
        sys.exit(1)
